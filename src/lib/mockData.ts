export function getChildById(id: string): Child | undefined {
  return mockChildren.find(c => c.id === id);
}

export function getAuthorizationById(id: string): Authorization | undefined {
  return mockAuthorizations.find(a => a.id === id);
}

export function getAuthorizationsByChildId(childId: string): Authorization[] {
  return mockAuthorizations.filter(a => a.childId === childId);
}

export function getPickupRecordById(id: string): PickupRecord | undefined {
  return mockPickupRecords.find(r => r.id === id);
}

export function getPickupRecordsByChildId(childId: string): PickupRecord[] {
  return mockPickupRecords.filter(r => r.childId === childId);
}

export function getHistoryNodesByRecordId(recordId: string): PickupHistoryNode[] {
  return mockPickupHistoryNodes.filter(n => n.pickupRecordId === recordId).sort((a, b) => 
    new Date(a.timestamp).getTime() - new Date(b.timestamp).getTime()
  );
}

export function getPickupRecordWithDetails(id: string): (PickupRecord & { child?: Child; authorization?: Authorization; historyNodes?: PickupHistoryNode[] }) | undefined {
  const record = getPickupRecordById(id);
  if (!record) return undefined;
  
  return {
    ...record,
    child: getChildById(record.childId),
    authorization: record.authorizationId ? getAuthorizationById(record.authorizationId) : undefined,
    historyNodes: getHistoryNodesByRecordId(id),
  };
}
